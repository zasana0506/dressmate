def normalize_color(raw):
    """把自由文本色名归一化到上面的固定色表。

    视觉模型和手工录入都可能写「藏青色」「深蓝色」「奶白色」这类描述，
    若直接参与配色打分，会因为不在表里而被当成点缀色，导致配色分失真。
    """
    if not raw:
        return "黑"
    c = str(raw).strip().replace(" ", "")
    for suffix in ("色系", "色"):
        if c.endswith(suffix) and len(c) > len(suffix):
            c = c[: -len(suffix)]
            break
    if c in NEUTRAL_COLORS or c in COLOR_FAMILY:
        return c
    # 包含匹配：深藏青 → 藏青、浅米白 → 米白（长词优先，避免「米」抢先）
    known = sorted({k for k in list(NEUTRAL_COLORS) + list(COLOR_FAMILY) if k},
                   key=len, reverse=True)
    for k in known:
        if k in c:
            return k
    return c

